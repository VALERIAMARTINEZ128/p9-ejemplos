print("\n===== 2. MÚLTIPLES VARIABLES =====")

# Ejemplo 1
nombre, edad = "Valeria", 16
print("Nombre:", nombre)
print("Edad:", edad)

# Ejemplo 2
x, y, z = 10, 20, 30
print("X:", x)
print("Y:", y)
print("Z:", z)

# Ejemplo 3
materia, semestre, grupo = "Python", 2, "3H"
print("Materia:", materia)
print("Semestre:", semestre)
print("Grupo:", grupo)


print("\n===== 3. TIPOS DE DATOS =====")

# Ejemplo 1: String
nombre = "Valeria"
print("Nombre:", nombre)
print("Tipo:", type(nombre))

# Ejemplo 2: Integer
edad = 16
print("Edad:", edad)
print("Tipo:", type(edad))

# Ejemplo 3: Float
promedio = 9.5
print("Promedio:", promedio)
print("Tipo:", type(promedio))


print("\n===== 4. OPERADORES ARITMÉTICOS =====")

# Ejemplo 1: Suma
a = 10
b = 5
resultado = a + b
print("Suma:", resultado)

# Ejemplo 2: Resta
a = 20
b = 8
resultado = a - b
print("Resta:", resultado)

# Ejemplo 3: Multiplicación
precio = 50
cantidad = 3
resultado = precio * cantidad
print("Multiplicación:", resultado)


print("\n===== 5. OPERADORES DE COMPARACIÓN =====")

# Ejemplo 1: Igual
edad = 16
print("¿Edad igual a 16?:", edad == 16)

# Ejemplo 2: Mayor que
calificacion = 9
print("¿Calificación mayor que 6?:", calificacion > 6)

# Ejemplo 3: Menor que
edad = 15
print("¿Edad menor que 18?:", edad < 18)


print("\n===== 6. OPERADORES LÓGICOS =====")

# Ejemplo 1: AND
edad = 16
calificacion = 9
print("AND:", edad >= 15 and calificacion >= 6)

# Ejemplo 2: OR
dia = "sábado"
print("OR:", dia == "sábado" or dia == "domingo")

# Ejemplo 3: NOT
llueve = False
print("NOT:", not llueve)
